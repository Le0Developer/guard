CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    email text NOT NULL DEFAULT '',
    password text NOT NULL DEFAULT '',
    role text NOT NULL DEFAULT 'User' CHECK (role IN ('User','Admin')),
    disabled boolean NOT NULL DEFAULT false,
    mfa_revision bigint NOT NULL DEFAULT 0,
    mfa_failures integer NOT NULL DEFAULT 0,
    mfa_window timestamptz,
    webauthn_user_id bytea NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE sessions (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    token_hash text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX ON sessions (user_id);

CREATE INDEX ON sessions (expires_at);

CREATE TABLE login_sessions (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    token_hash text NOT NULL UNIQUE,
    internal_token text NOT NULL,
    redirect_uri text NOT NULL DEFAULT '/',
    provider text NOT NULL DEFAULT '',
    state jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX ON login_sessions (expires_at);

CREATE TABLE groups (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE group_members (
    group_id bigint NOT NULL REFERENCES groups(id),
    user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id,user_id)
);

CREATE INDEX ON group_members (group_id);

CREATE INDEX ON group_members (user_id);

CREATE TABLE clients (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE,
    client_type text NOT NULL CHECK (client_type IN ('Oidc','ForwardAuth')),
    client_id text NOT NULL UNIQUE,
    client_secret text NOT NULL,
    session_lifetime_s integer NOT NULL DEFAULT 64800 CHECK (session_lifetime_s > 0),
    require_pkce boolean NOT NULL DEFAULT true,
    detailed_logging boolean NOT NULL DEFAULT false,
    allow_event_reports boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE client_redirects (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES clients(id),
    redirect_uri text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON client_redirects (client_id);

CREATE TABLE client_access_rules (
    client_id bigint NOT NULL REFERENCES clients(id),
    group_id bigint NOT NULL REFERENCES groups(id),
    priority smallint NOT NULL,
    access_control text NOT NULL CHECK (access_control IN ('Allow','Deny')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (client_id,group_id)
);

CREATE INDEX ON client_access_rules (client_id);

CREATE INDEX ON client_access_rules (group_id);

CREATE TABLE authorization_codes (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES clients(id),
    user_id bigint NOT NULL REFERENCES users(id),
    session_id bigint NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    redirect_uri text NOT NULL,
    pkce_challenge text NOT NULL DEFAULT '',
    pkce_method text NOT NULL DEFAULT '',
    scope text NOT NULL,
    nonce text NOT NULL DEFAULT '',
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON authorization_codes (client_id);

CREATE INDEX ON authorization_codes (user_id);

CREATE INDEX ON authorization_codes (session_id);

CREATE INDEX ON authorization_codes (expires_at);

CREATE TABLE oauth_tokens (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES clients(id),
    user_id bigint NOT NULL REFERENCES users(id),
    session_id bigint NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    code_id bigint NOT NULL REFERENCES authorization_codes(id) ON DELETE CASCADE,
    family text NOT NULL,
    access_token_hash text NOT NULL UNIQUE,
    refresh_token_hash text NOT NULL UNIQUE,
    scope text NOT NULL,
    nonce text NOT NULL DEFAULT '',
    auth_time bigint NOT NULL,
    access_expires_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON oauth_tokens (client_id);

CREATE INDEX ON oauth_tokens (user_id);

CREATE INDEX ON oauth_tokens (session_id);

CREATE INDEX ON oauth_tokens (code_id);

CREATE INDEX ON oauth_tokens (expires_at);

CREATE TABLE signing_keys (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES clients(id),
    key bytea NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX ON signing_keys (client_id);

CREATE INDEX ON signing_keys (expires_at);

CREATE TABLE totp_authenticators (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    name text NOT NULL,
    secret text NOT NULL,
    last_step bigint NOT NULL DEFAULT -1,
    last_used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON totp_authenticators (user_id);

CREATE TABLE webauthn_credentials (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    credential_id text NOT NULL UNIQUE,
    name text NOT NULL,
    credential jsonb NOT NULL,
    sign_count bigint NOT NULL DEFAULT 0,
    last_used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON webauthn_credentials (user_id);

CREATE TABLE recovery_codes (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    hash text NOT NULL UNIQUE,
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON recovery_codes (user_id);

CREATE TABLE mfa_ceremonies (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    token_hash text NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users(id),
    actor_id bigint NOT NULL REFERENCES users(id),
    session_id bigint REFERENCES sessions(id) ON DELETE CASCADE,
    login_session_id bigint REFERENCES login_sessions(id) ON DELETE CASCADE,
    revision bigint NOT NULL,
    purpose text NOT NULL,
    state jsonb NOT NULL,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    attempts integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON mfa_ceremonies (user_id);

CREATE INDEX ON mfa_ceremonies (actor_id);

CREATE INDEX ON mfa_ceremonies (session_id);

CREATE INDEX ON mfa_ceremonies (login_session_id);

CREATE INDEX ON mfa_ceremonies (expires_at);

CREATE TABLE forward_auth_requests (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    state_hash text NOT NULL UNIQUE,
    browser_hash text NOT NULL,
    code_hash text UNIQUE,
    client_id bigint NOT NULL REFERENCES clients(id),
    origin text NOT NULL,
    return_uri text NOT NULL,
    user_id bigint REFERENCES users(id),
    session_id bigint REFERENCES sessions(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON forward_auth_requests (client_id);

CREATE INDEX ON forward_auth_requests (user_id);

CREATE INDEX ON forward_auth_requests (session_id);

CREATE INDEX ON forward_auth_requests (expires_at);

