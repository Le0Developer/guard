CREATE TABLE audit_logs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    event text NOT NULL,
    data jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON audit_logs (user_id);

CREATE TABLE access_logs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id text NOT NULL UNIQUE,
    dedupe_key text NOT NULL UNIQUE,
    client_id bigint NOT NULL REFERENCES clients(id),
    user_id bigint REFERENCES users(id),
    session_id bigint,
    source text NOT NULL,
    data jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON access_logs (client_id);

CREATE INDEX ON access_logs (user_id);

CREATE INDEX ON access_logs (session_id);

CREATE TABLE access_log_deliveries (
    log_id bigint PRIMARY KEY REFERENCES access_logs(id),
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    delivered_at timestamptz,
    last_error text NOT NULL DEFAULT ''
);

CREATE INDEX ON access_log_deliveries (log_id);

CREATE TABLE event_report_rates (
    client_id bigint PRIMARY KEY REFERENCES clients(id),
    window_start bigint NOT NULL,
    count integer NOT NULL
);

